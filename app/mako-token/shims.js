'use strict';
// S35 mako-token: the launchers in %APPDATA%\Mako\bin. Pure content generation plus an idempotent
// writer; nothing here touches a token or the key.
//
//   gh, gh.cmd, gh.ps1    the gh shim for Git Bash, cmd and PowerShell (gh-shim.js)
//   git-credential-mako   git's credential helper for github.com (cli.js git); git runs it via sh
//   mako-claude.cmd       the interim launcher: a plain terminal that starts `claude` with the same
//                         App-mode environment a Mako pane gets (cli.js launch; docs/MAKO-TOKEN.md)
//
// Every path baked into a launcher is checked against characters that could change what a shell
// runs; an unsafe path is refused, never escaped.

const path = require('path');
const nodefs = require('fs');
const { MakoTokenError } = require('./errors');

const UNSAFE_PATH = /['"%!^&|<>`$\r\n\0]/;

function assertSafePath(p, label) {
  if (typeof p !== 'string' || !p || UNSAFE_PATH.test(p)) {
    throw new MakoTokenError('unsafe-path', `${label} contains a character that is not allowed in a launcher path (one of ' " % ! ^ & | < > \` $ or a line break)`);
  }
  return p;
}

const posix = (p) => p.replace(/\\/g, '/');

/** The git credential.helper value for github.com: git appends " get" and runs it through sh. */
function gitHelperValue(binDir) {
  assertSafePath(binDir, 'the launcher folder');
  return `!'${posix(path.join(binDir, 'git-credential-mako'))}'`;
}

function shFile(lines) { return lines.join('\n') + '\n'; }
function crlf(lines) { return lines.join('\r\n') + '\r\n'; }

/**
 * launcherFiles({ runtime:{exe, runAsNode}, ghShimJs, cliJs, binDir }) -> { name: content }
 */
function launcherFiles({ runtime, ghShimJs, cliJs, binDir }) {
  const exe = assertSafePath(runtime.exe, 'the Node or Electron path');
  assertSafePath(ghShimJs, 'the gh shim path');
  assertSafePath(cliJs, 'the mako-token path');
  assertSafePath(binDir, 'the launcher folder');
  const asNode = runtime.runAsNode === true;
  const shRun = (script, rest) => `${asNode ? 'ELECTRON_RUN_AS_NODE=1 ' : ''}exec '${posix(exe)}' '${posix(script)}'${rest}`;
  const cmdRun = (script, rest) => [
    'setlocal', ...(asNode ? ['set "ELECTRON_RUN_AS_NODE=1"'] : []),
    `"${exe}" "${script}"${rest}`, 'exit /b %ERRORLEVEL%',
  ];

  const files = {};
  files.gh = shFile(['#!/bin/sh', '# Generated by Mako (S35). Do not edit; Mako rewrites it.', shRun(ghShimJs, ' "$@"')]);
  files['git-credential-mako'] = shFile(['#!/bin/sh', '# Generated by Mako (S35). Do not edit; Mako rewrites it.', shRun(cliJs, ' git "$@"')]);
  files['gh.cmd'] = crlf(['@echo off', 'rem Generated by Mako (S35). Do not edit; Mako rewrites it.', ...cmdRun(ghShimJs, ' %*')]);
  files['gh.ps1'] = crlf([
    '# Generated by Mako (S35). Do not edit; Mako rewrites it.',
    ...(asNode ? ["$env:ELECTRON_RUN_AS_NODE = '1'"] : []),
    'try {', `  & '${exe}' '${ghShimJs}' @args`, '  $code = $LASTEXITCODE', '} finally {',
    ...(asNode ? ['  Remove-Item Env:ELECTRON_RUN_AS_NODE -ErrorAction SilentlyContinue'] : []), '}',
    'exit $code',
  ]);
  // The interim launcher: a plain terminal runs `mako-claude` and gets claude with the same
  // App-mode environment a Mako pane gets (cli.js launch builds it with the pane's own builder).
  files['mako-claude.cmd'] = crlf([
    '@echo off', 'rem Generated by Mako (S35). Starts claude with the GitHub App identity.',
    ...cmdRun(cliJs, ' launch claude %*'),
  ]);
  return files;
}

/** Write the launchers that differ from what is on disk. Returns the names written. */
function installLaunchers({ fs = nodefs, binDir, files }) {
  fs.mkdirSync(binDir, { recursive: true });
  const written = [];
  for (const [name, content] of Object.entries(files)) {
    const file = path.join(binDir, name);
    let current = null;
    try { current = fs.readFileSync(file, 'utf8'); } catch { /* new file */ }
    if (current === content) continue;
    const tmp = `${file}.${process.pid}.tmp`;
    fs.writeFileSync(tmp, content, { mode: 0o755 });
    fs.renameSync(tmp, file);
    written.push(name);
  }
  return written;
}

module.exports = { assertSafePath, gitHelperValue, launcherFiles, installLaunchers, UNSAFE_PATH };
